// Writes the data behind `Foundations/Icons`: which lucide icons the DS
// components and JustRAG import, one entry per glyph (aliases such as
// `Loader2` resolved to `LoaderCircle`), and a registry that imports exactly
// those glyphs, so the page does not ship all of lucide.
//
//   node scripts/icon-usage.mjs ../JLURAG   # DS components and JustRAG
//   node scripts/icon-usage.mjs             # DS components; keeps the JustRAG snapshot
//
// Out: src/docs/icon-usage.json, src/docs/icon-registry.ts. A unit test
// (src/docs/icon-usage.test.ts) fails when a component's icons and the JSON
// drift apart.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import * as lucide from "lucide-react";

const JSON_OUT = "src/docs/icon-usage.json";
const REGISTRY_OUT = "src/docs/icon-registry.ts";

/** The canonical name of every glyph, keyed by the component object any of its names resolve to. */
const canonical = new Map(Object.entries(lucide.icons).map(([name, glyph]) => [glyph, name]));
const unknown = new Set();
const canonicalName = (name) => {
  const glyph = canonical.get(lucide[name]);
  if (!glyph) unknown.add(name);
  return glyph;
};

/** Source files under `dir`: .ts/.tsx, without tests, stories and test fixtures. */
function* sources(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (name === "node_modules" || name === "test") continue;
    if (statSync(path).isDirectory()) yield* sources(path);
    else if (/\.tsx?$/.test(name) && !/\.(test|stories)\.tsx?$/.test(name) && !name.endsWith(".d.ts")) yield path;
  }
}

/** The names a source imports from lucide-react. */
function lucideImports(source) {
  const names = [];
  for (const match of source.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']lucide-react["']/g)) {
    for (const part of match[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/)[0].trim();
      if (/^[A-Z]/.test(name) && !name.startsWith("Lucide")) names.push(name);
    }
  }
  return names;
}

/** DS components (src/components, one entry per file name) that draw each glyph. */
const ds = {};
for (const path of sources("src/components")) {
  const component = basename(path).replace(/\.tsx?$/, "");
  for (const name of lucideImports(readFileSync(path, "utf8"))) {
    const glyph = canonicalName(name);
    if (!glyph) continue;
    (ds[glyph] ??= new Set()).add(component);
  }
}

/** JustRAG: distinct files per glyph, and the names it was imported as. */
let justrag;
const repo = process.argv[2];
if (repo) {
  const root = join(repo, "web/src");
  const files = {};
  const names = {};
  for (const path of sources(root)) {
    for (const name of lucideImports(readFileSync(path, "utf8"))) {
      const glyph = canonicalName(name);
      if (!glyph) continue;
      (files[glyph] ??= new Set()).add(relative(root, path));
      (names[glyph] ??= new Set()).add(name);
    }
  }
  const git = (...args) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" }).trim();
  justrag = {
    ref: `${git("branch", "--show-current")} ${git("log", "-1", "--format=%h, %cs")}`,
    icons: Object.fromEntries(
      Object.keys(files)
        .sort()
        .map((glyph) => [glyph, { files: files[glyph].size, names: [...names[glyph]].sort() }]),
    ),
  };
} else if (existsSync(JSON_OUT)) {
  justrag = JSON.parse(readFileSync(JSON_OUT, "utf8")).justrag;
} else {
  console.error("no JustRAG snapshot yet: node scripts/icon-usage.mjs <path to a JustRAG checkout>");
  process.exit(1);
}

const data = {
  ds: Object.fromEntries(Object.keys(ds).sort().map((glyph) => [glyph, [...ds[glyph]].sort()])),
  justrag,
};
writeFileSync(JSON_OUT, `${JSON.stringify(data, null, 2)}\n`);

const glyphs = [...new Set([...Object.keys(data.ds), ...Object.keys(data.justrag.icons)])].sort();
writeFileSync(
  REGISTRY_OUT,
  `// Generated by scripts/icon-usage.mjs — do not edit by hand; run the script again.
// Every glyph in icon-usage.json, imported by name so the page ships only these.
import type { LucideIcon } from "lucide-react";
import {
${glyphs.map((g) => `  ${g},`).join("\n")}
} from "lucide-react";

export const ICON_REGISTRY: Record<string, LucideIcon> = {
${glyphs.map((g) => `  ${g},`).join("\n")}
};
`,
);
if (unknown.size > 0) console.warn(`not a lucide icon in this version, left out: ${[...unknown].sort().join(", ")}`);
console.log(`${glyphs.length} glyphs — DS ${Object.keys(data.ds).length}, JustRAG ${Object.keys(justrag.icons).length} (${justrag.ref})`);
